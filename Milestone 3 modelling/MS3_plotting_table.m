function result = MS3_plotting_table(runs)
% Pair predicted and fitted coefficients; both errors are absolute differences.
result = table(runs.bolt_count,runs.distance_mm,runs.cart_stop_s, ...
    runs.model_b_s_inv,runs.fit_b_s_inv,abs(runs.fit_b_s_inv-runs.model_b_s_inv), ...
    runs.model_lambda_s_inv,runs.fit_lambda_s_inv,abs(runs.fit_lambda_s_inv-runs.model_lambda_s_inv), ...
    runs.fit_c_Nm_s_rad,'VariableNames', ...
    {'Bolts','Travel distance (mm)','Cart stop time (s)', ...
    'Predicted b (s⁻¹)','Fitted b (s⁻¹)','Absolute b error (s⁻¹)', ...
    'Predicted λ (s⁻¹)','Fitted λ (s⁻¹)','Absolute λ error (s⁻¹)','Fitted c (N·m·s/rad)'});
end
